"""Recurrence set: RRULE + RDATE - EXDATE (RFC 5545, section 3.8.5).

The final set is every value generated by the rule or listed in RDATE,
without the values listed in EXDATE (RSET-01). EXDATE wins over both
inclusion properties (RSET-02), and a value produced by both the rule and
RDATE appears once (RSET-03). Values are merged lazily with ``heapq.merge``,
so an infinite rule stays infinite and cheap.

Time zones are applied here, on top of the zone-agnostic generator (D-02).
For a rule with a TZID:

- an RRULE instance whose local time does not exist is dropped and not
  counted in COUNT (TZ-03), through the ``is_valid`` hook of ``expand``;
- explicit values (DTSTART, RDATE, EXDATE) in a gap are shifted with the
  offset before the gap (TZ-02); a time in a fold is its first occurrence
  (TZ-01);
- EXDATE is compared with instances as a UTC instant, so it may be given in
  any zone;
- the instances are aware datetimes with a fixed offset named after the zone.
"""

from __future__ import annotations

import heapq
from collections.abc import Iterable, Iterator
from datetime import date, datetime, timezone

from recurkit.errors import TimeZoneError
from recurkit.expand import Occurrence
from recurkit.expand import occurrences as rule_occurrences
from recurkit.rule.model import Rule
from recurkit.timezones import TimeZoneProvider, ZoneInfoProvider


def unique_sorted(values: Iterable[Occurrence]) -> list[Occurrence]:
    """Sort explicit dates and drop duplicates."""
    return sorted(set(values))


def merge_unique(*streams: Iterable[Occurrence]) -> Iterator[Occurrence]:
    """Merge increasing streams into one increasing stream without duplicates (RSET-03)."""
    previous: Occurrence | None = None
    for value in heapq.merge(*streams):
        if value != previous:
            yield value
            previous = value


def _same_kind(value: Occurrence, reference: Occurrence, zoned: bool) -> bool:
    if isinstance(reference, datetime):
        if not isinstance(value, datetime):
            return False
        # In a zoned set a naive value is local time of the zone and an aware
        # value is an instant; both are allowed.
        return zoned or (value.tzinfo is None) == (reference.tzinfo is None)
    return isinstance(value, date) and not isinstance(value, datetime)


class RecurrenceSet:
    """A rule with added (RDATE) and excluded (EXDATE) start values.

    RDATE and EXDATE values must have the same kind as DTSTART: dates for an
    all-day rule, naive date-times for a floating rule, aware date-times for
    a UTC rule. For a rule with a TZID, naive values are local times of that
    zone and aware values are instants in any zone.

    ``provider`` resolves the rule's TZID; :class:`ZoneInfoProvider` is used
    when none is given.
    """

    def __init__(
        self,
        rule: Rule,
        rdates: Iterable[Occurrence] = (),
        exdates: Iterable[Occurrence] = (),
        *,
        provider: TimeZoneProvider | None = None,
    ):
        self.rule = rule
        dtstart = rule.require_dtstart()
        self.tzid = rule.tzid
        self.provider: TimeZoneProvider | None = None
        if self.tzid is not None:
            self.provider = provider if provider is not None else ZoneInfoProvider()
            self.provider.check_zone(self.tzid)
        explicit = (tuple(rdates), tuple(exdates))
        for value in (*explicit[0], *explicit[1]):
            if not _same_kind(value, dtstart, self.zoned):
                raise TypeError(f"{value!r} is not the same kind of value as DTSTART {dtstart!r}")
        self.rdates = tuple(unique_sorted(self._place(v) for v in explicit[0]))
        self.exdates = frozenset(self._place(v) for v in explicit[1])

    @property
    def zoned(self) -> bool:
        return self.tzid is not None

    def _zone(self) -> tuple[TimeZoneProvider, str]:
        if self.provider is None or self.tzid is None:
            raise TimeZoneError("the rule has no TZID")
        return self.provider, self.tzid

    def _place(self, value: Occurrence) -> Occurrence:
        """Put an explicit value on the time line of the set (TZ-01, TZ-02)."""
        if not self.zoned or not isinstance(value, datetime):
            return value
        provider, tzid = self._zone()
        if value.tzinfo is not None:  # an instant: keep it, show it in the zone
            return value.astimezone(timezone(provider.utc_offset(tzid, value), tzid))
        return provider.localize(tzid, value)

    def _rule_values(self) -> Iterator[Occurrence]:
        if not self.zoned:
            yield from rule_occurrences(self.rule)
            return
        provider, tzid = self._zone()
        dtstart = self.rule.require_dtstart()

        def exists(local: Occurrence) -> bool:
            # DTSTART is an explicit value: shifted, never dropped (TZ-02).
            if local == dtstart or not isinstance(local, datetime):
                return True
            return provider.exists(tzid, local)

        until = self.rule.until
        local_until = None
        if isinstance(until, datetime) and until.tzinfo is not None:
            local_until = provider.to_local(tzid, until)
        for local in rule_occurrences(self.rule, is_valid=exists, until=local_until):
            yield self._place(local)

    def _included(self) -> Iterator[Occurrence]:
        return merge_unique(self._rule_values(), self.rdates)

    def __iter__(self) -> Iterator[Occurrence]:
        """All values of the set in increasing order (RSET-01, RSET-02)."""
        for value in self._included():
            if value not in self.exdates:
                yield value

    def __repr__(self) -> str:
        zone = f", tzid={self.tzid!r}" if self.tzid else ""
        return (
            f"RecurrenceSet({self.rule.to_text()!r}, dtstart={self.rule.dtstart!r}{zone}, "
            f"rdates={len(self.rdates)}, exdates={len(self.exdates)})"
        )
